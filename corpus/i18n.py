def translate(ui_lang: str, key: str, **kwargs: object) -> str:
    """翻译一个 UI 文案；未知语言或 key 都安全回退到中文。"""
    language = ui_lang if ui_lang in TRANSLATIONS else "zh"
    text = TRANSLATIONS[language].get(key, TRANSLATIONS["zh"].get(key, key))
    try:
        return text.format(**kwargs)
    except (KeyError, ValueError):
        return text


