def genre_label(value: str, ui_lang: str) -> str:
    """返回 genre 的界面显示名，绝不改变其数据库或查询参数原值。"""
    if ui_lang == "en":
        return GENRE_LABELS.get(value, value)
    return value


def compact_language_label(code: str, ui_lang: str) -> str:
    """返回仅供搜索命中窄 badge 使用的语言缩写。"""
    labels = (
        {"zh": "CN", "ja": "JP", "en": "EN"}
        if ui_lang == "en"
        else {"zh": "中", "ja": "日", "en": "英"}
    )
    return labels.get(code, code)
